// Build-time helper: compiles the HLSL of the Direct3D 11 back end (src/hd_shaders_hlsl.hpp) to DXBC and writes
// it as a C++ include (build/hd_shaders.inc). The renderer then needs no shader compiler at run time, which is
// what makes it work under Wine/Proton, where d3dcompiler_47 may not compile these shaders.
//   compile_shaders <output.inc>
#define WIN32_LEAN_AND_MEAN
#define NOMINMAX
#include <windows.h>
#include <d3dcompiler.h>
#include <cstdio>
#include <cstring>
#include "hd_shaders_hlsl.hpp"

int main(int argc, char** argv) {
    if (argc != 2) { std::fprintf(stderr, "usage: compile_shaders <output.inc>\n"); return 2; }
    const char* source = rrhd::gpuHlsl();
    int count = 0;
    const rrhd::GpuShaderEntry* entries = rrhd::gpuShaderEntries(count);
    FILE* out = nullptr;
    if (fopen_s(&out, argv[1], "wb") != 0 || !out) { std::fprintf(stderr, "cannot write %s\n", argv[1]); return 1; }
    std::fprintf(out, "// Generated by tools/compile_shaders.cpp. Do not edit.\n");
    for (int i = 0; i < count; ++i) {
        ID3DBlob *code = nullptr, *errors = nullptr;
        HRESULT hr = D3DCompile(source, std::strlen(source), "hd_gpu.hlsl", nullptr, nullptr, entries[i].name, entries[i].target,
                                D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, &code, &errors);
        if (FAILED(hr)) {
            std::fprintf(stderr, "shader %s failed: %s\n", entries[i].name, errors ? static_cast<const char*>(errors->GetBufferPointer()) : "?");
            std::fclose(out); return 1;
        }
        if (errors) errors->Release();
        const unsigned char* bytes = static_cast<const unsigned char*>(code->GetBufferPointer());
        std::fprintf(out, "static const unsigned char rrhdDxbc_%s[] = {", entries[i].name);
        for (SIZE_T k = 0; k < code->GetBufferSize(); ++k) std::fprintf(out, "%s%u,", (k % 24 == 0) ? "\n" : "", bytes[k]);
        std::fprintf(out, "\n};\n");
        code->Release();
    }
    std::fprintf(out, "static const struct { const char* name; const unsigned char* data; size_t size; } rrhdDxbcTable[] = {\n");
    for (int i = 0; i < count; ++i)
        std::fprintf(out, "    { \"%s\", rrhdDxbc_%s, sizeof rrhdDxbc_%s },\n", entries[i].name, entries[i].name, entries[i].name);
    std::fprintf(out, "};\n");
    std::fclose(out);
    std::printf("compiled %d shaders\n", count);
    return 0;
}
